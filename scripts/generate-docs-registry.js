import fs from 'fs';
import path from 'path';

const ROOT_DIR = process.cwd();
const DESIGN_HISTORY_DIR = path.join(ROOT_DIR, 'design-history');
const AUDIT_REPORTS_DIR = path.join(ROOT_DIR, 'audit-reports');
const DOCS_DIR = path.join(ROOT_DIR, 'docs');
const OUTPUT_FILE = path.join(ROOT_DIR, 'apps', 'web', 'src', 'addons', 'discovery', 'data', 'docsRegistry.ts');

function getFriendlyTitle(filename, content) {
  // Try to find first H1 header (# Title)
  const h1Match = content.match(/^#\s+(.+)$/m);
  if (h1Match) return h1Match[1].trim();

  // Otherwise, clean up filename
  return filename
    .replace(/^\d+_/g, '')
    .replace(/\.md$/g, '')
    .split(/[-_]/)
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}

function processDirectory(dirPath, category) {
  const items = [];
  if (!fs.existsSync(dirPath)) return items;

  const files = fs.readdirSync(dirPath);
  for (const file of files) {
    const filePath = path.join(dirPath, file);
    const stat = fs.statSync(filePath);

    if (stat.isFile() && file.endsWith('.md')) {
      const content = fs.readFileSync(filePath, 'utf-8');
      const title = getFriendlyTitle(file, content);
      const sizeKB = (stat.size / 1024).toFixed(1) + ' KB';
      const lastUpdated = stat.mtime.toISOString().split('T')[0];
      const id = file.toLowerCase().replace(/[^a-z0-9]/g, '_');

      items.push({
        id,
        title,
        filename: file,
        category,
        content,
        size: sizeKB,
        lastUpdated
      });
    }
  }
  return items;
}

function main() {
  console.log('Generating documentation registry...');
  
  let docs = [];

  // 1. Scan Root Files
  const rootFiles = ['DESIGN_HISTORY.md', 'CROSSANGLE.md', 'PRD.md', 'GEMINI.md', 'CLAUDE.md'];
  for (const file of rootFiles) {
    const filePath = path.join(ROOT_DIR, file);
    if (fs.existsSync(filePath)) {
      const content = fs.readFileSync(filePath, 'utf-8');
      const stat = fs.statSync(filePath);
      const title = getFriendlyTitle(file, content);
      const sizeKB = (stat.size / 1024).toFixed(1) + ' KB';
      const lastUpdated = stat.mtime.toISOString().split('T')[0];
      const id = file.toLowerCase().replace(/[^a-z0-9]/g, '_');

      docs.push({
        id,
        title,
        filename: file,
        category: 'Core Standards & Specs',
        content,
        size: sizeKB,
        lastUpdated
      });
    }
  }

  // 2. Scan Design History files
  docs = docs.concat(processDirectory(DESIGN_HISTORY_DIR, 'Design History Logs'));

  // 3. Scan Audit Reports
  docs = docs.concat(processDirectory(AUDIT_REPORTS_DIR, 'Engineering Audits'));

  // 4. Scan main docs directory
  if (fs.existsSync(DOCS_DIR)) {
    const mainDocs = fs.readdirSync(DOCS_DIR);
    for (const file of mainDocs) {
      const filePath = path.join(DOCS_DIR, file);
      const stat = fs.statSync(filePath);
      if (stat.isFile() && file.endsWith('.md')) {
        const content = fs.readFileSync(filePath, 'utf-8');
        const title = getFriendlyTitle(file, content);
        const sizeKB = (stat.size / 1024).toFixed(1) + ' KB';
        const lastUpdated = stat.mtime.toISOString().split('T')[0];
        const id = file.toLowerCase().replace(/[^a-z0-9]/g, '_');

        docs.push({
          id,
          title,
          filename: file,
          category: 'Guides & Manuals',
          content,
          size: sizeKB,
          lastUpdated
        });
      }
    }
  }

  // Ensure output directory exists
  const outputDir = path.dirname(OUTPUT_FILE);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Write content to Output File
  const jsonContent = JSON.stringify(docs, null, 2);
  const tsContent = `// This file is auto-generated by scripts/generate-docs-registry.js
// Do not modify directly.

export interface DocItem {
  id: string;
  title: string;
  filename: string;
  category: string;
  content: string;
  size: string;
  lastUpdated: string;
}

export const docsRegistry: DocItem[] = ${jsonContent};
`;

  fs.writeFileSync(OUTPUT_FILE, tsContent, 'utf-8');
  console.log(`Successfully generated registry at: ${OUTPUT_FILE} (${docs.length} documents compiled)`);
}

main();
