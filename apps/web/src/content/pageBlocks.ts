const GOOGLE_MAPS_HOSTS = ["www.google.com", "google.com", "maps.google.com", "www.google.co.in", "maps.app.goo.gl", "goo.gl"];
export function isGoogleMapsUrl(value: string): boolean {
  try {
    const u = new URL(value);
    return u.protocol === "https:" && GOOGLE_MAPS_HOSTS.includes(u.hostname);
  } catch {
    return false;
  }
}

